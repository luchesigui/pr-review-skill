#!/usr/bin/env python3
"""Regenerate the generated half of a configured Figma map markdown file.

Everything above the generated marker in the map file is hand-written and preserved.
Below it, this script writes the project/folder/file tree from <STATE_DIR>/figma/inventory.json
and each file's pages and top-level frames from the Figma REST API.

Configuration lives in <STATE_DIR>/figma/config.json:
{
  "org_id": "...",
  "team_url": "https://www.figma.com/files/.../team/...",
  "output_file": "/path/to/Figma map.md",
  "token_file": "~/.config/figma/token",
  "pages_only_projects": ["Design System"],
  "pages_only_folders": ["Archive"],
  "marker": "<!-- generated by ~/.claude/skills/review-pr/figma/figma_map.py; edit above this line only -->"
}
"""
import json
import os
import re
import sys
import time
import urllib.request
from collections import OrderedDict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "scripts"))
import common

WIDTHS = {1920: 1920, 1440: 1440, 1366: 1366, 1280: 1280, 1024: 1024, 768: 768, 414: 375, 390: 375, 375: 375, 360: 375, 320: 320}
SKIP_PAGE = re.compile(r"^\W*(thumbnail|cover|local components)\W*$", re.I)
DIVIDER = re.compile(r"^[\s\-–—_=.]*$")
DEFAULT_MARK = "<!-- generated by review-pr/figma/figma_map.py; edit above this line only -->"


def load_figma_config():
    fdir = os.path.join(common.state_dir(), "figma")
    cfg_path = os.path.join(fdir, "config.json")
    if not os.path.isfile(cfg_path):
        raise RuntimeError(
            f"Missing Figma map config at {cfg_path}. Create it with org_id, team_url, output_file, and inventory.json."
        )
    cfg = json.load(open(cfg_path, encoding="utf-8"))
    return fdir, cfg


def fetch(cache_dir, token_file, key, refresh):
    os.makedirs(cache_dir, exist_ok=True)
    path = os.path.join(cache_dir, f"{key}.json")
    if refresh or not os.path.exists(path):
        tok = open(os.path.expanduser(token_file), encoding="utf-8").read().strip()
        req = urllib.request.Request(f"https://api.figma.com/v1/files/{key}?depth=2", headers={"X-Figma-Token": tok})
        with urllib.request.urlopen(req, timeout=180) as r:
            open(path, "wb").write(r.read())
        time.sleep(1)
    return json.load(open(path, encoding="utf-8"))


def slug(name):
    return re.sub(r"[^A-Za-z0-9]+", "-", name).strip("-") or "file"


def frames_lines(page):
    groups = OrderedDict()
    for c in page.get("children", []):
        if c["type"] not in ("FRAME", "SECTION", "COMPONENT", "COMPONENT_SET"):
            continue
        w = round((c.get("absoluteBoundingBox") or {}).get("width") or 0)
        bp = WIDTHS.get(w)
        base = c["name"].strip()
        if bp:
            base = re.sub(r"[\s_-]*(1920|1440|1366|1280|1024|768|414|390|375|360|320)$", "", base) or base
        label = f'{bp} {c["id"]}' if bp else c["id"]
        if c["type"] == "SECTION":
            label = f'section {c["id"]}'
        groups.setdefault(base, []).append(label)
    return [f"- {k}: {', '.join(v)}" for k, v in groups.items()]


def main():
    refresh = "--refresh" in sys.argv
    fdir, cfg = load_figma_config()
    note = common.expand_path(cfg["output_file"])
    cache_dir = os.path.join(fdir, "cache")
    inv_path = os.path.join(fdir, "inventory.json")
    token_file = cfg.get("token_file") or "~/.config/figma/token"
    org = cfg.get("org_id") or ""
    team_url = cfg.get("team_url") or ""
    mark = cfg.get("marker") or DEFAULT_MARK
    pages_only_projects = set(cfg.get("pages_only_projects") or [])
    pages_only_folders = set(cfg.get("pages_only_folders") or ["Archive"])

    inv = json.load(open(inv_path, encoding="utf-8"))
    roots = sorted((i for i, f in inv.items() if not f["p"]), key=lambda i: inv[i]["n"].lower())
    kids = {i: sorted((c for c, f in inv.items() if f["p"] == i), key=lambda c: inv[c]["n"].lower()) for i in inv}

    intro = f"Team: {team_url}. " if team_url else ""
    out = [
        "## Projects and files",
        "",
        f"{intro}Files under `Dev` are typically built from; `Archive` is old; Design System projects hold component libraries. Pages and frames of each file are below.",
        "",
        "| Project | Folder | File | Last edit | Link |",
        "|---|---|---|---|---|",
    ]
    order = []
    for r in roots:
        for fid in [r] + kids[r]:
            sub = "" if fid == r else inv[fid]["n"]
            for key, (name, touched, typ) in sorted(inv[fid]["f"].items(), key=lambda kv: kv[1][0].lower()):
                kind = "board" if typ == "whiteboard" else "design"
                proj_cell = (
                    f'[{inv[r]["n"]}](https://www.figma.com/files/{org}/folder/{r})'
                    if org
                    else inv[r]["n"]
                )
                out.append(
                    f"| {proj_cell} | {sub} | {name.replace('|', chr(92) + '|')} | {touched} | "
                    f"https://www.figma.com/{kind}/{key}/{slug(name)} |"
                )
                order.append((r, fid, key, name, typ))
        if not any(inv[f]["f"] for f in [r] + kids[r]):
            proj_cell = (
                f'[{inv[r]["n"]}](https://www.figma.com/files/{org}/folder/{r})'
                if org
                else inv[r]["n"]
            )
            out.append(f"| {proj_cell} | | (no files) | | |")

    out += [
        "",
        "Pages after a `-----` divider page are usually archive or work in progress; they are listed but marked. "
        'Pages marked "(in progress)" are not final: treat a mismatch there as a question, not a finding. '
        "Design System and Archive files list pages only.",
        "",
    ]

    for r, fid, key, name, typ in order:
        try:
            j = fetch(cache_dir, token_file, key, refresh)
        except Exception as e:
            out += [f"## {name}", "", f"Could not read: {e}", ""]
            continue
        pages_only = inv[r]["n"] in pages_only_projects or inv[fid]["n"] in pages_only_folders or typ == "whiteboard"
        where = inv[r]["n"] + ("" if fid == r else f' / {inv[fid]["n"]}')
        out += [f"## {name}", "", f"{where}. https://www.figma.com/design/{key}/{slug(name)}", ""]
        after_divider = False
        for pg in j["document"].get("children", []):
            pname = pg["name"].strip()
            if DIVIDER.match(pname):
                after_divider = True
                continue
            if SKIP_PAGE.match(pname):
                continue
            mark_txt = " (after divider)" if after_divider and not pages_only else ""
            n = sum(1 for c in pg.get("children", []) if c["type"] in ("FRAME", "SECTION", "COMPONENT", "COMPONENT_SET"))
            if pages_only:
                out.append(f'- {pname} ({pg["id"]}){mark_txt}: {n} frames')
            else:
                out += [f'### {pname} ({pg["id"]}){mark_txt}'] + frames_lines(pg)
        out.append("")

    if os.path.isfile(note):
        text = open(note, encoding="utf-8").read()
        head = text.split(mark)[0].rstrip() + "\n\n" if mark in text else text.rstrip() + "\n\n"
    else:
        os.makedirs(os.path.dirname(note), exist_ok=True)
        head = "# Figma map\n\n"
    open(note, "w", encoding="utf-8").write(head + mark + "\n\n" + "\n".join(out).rstrip() + "\n")
    print(f"{len(order)} files written to {note}")


if __name__ == "__main__":
    main()
