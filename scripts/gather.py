#!/usr/bin/env python3
"""Deterministic Step 1 context gatherer for /review-pr (review and recheck modes).

Stdlib-only so `python3 -I` always works. Repo-agnostic and config-driven via common.py.
Prepares <DIR>/ with PR metadata, diff, paginated existing comments, worktree at PR head
(pinned by SHA), author mannerisms, related PR notes, full instruction chain (AGENTS.md /
CLAUDE.md), optional repo profile, configured extra linters, targeted Figma map slice, and
routing metadata (meta.json).

Usage:
    python3 -I gather.py <pr> --dir <DIR> [--mode review|recheck] [--old-head <sha>]
                        [--repo <git-dir>] [--gh-repo <owner/name>]
"""
