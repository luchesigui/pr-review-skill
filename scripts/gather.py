BOT_LOGINS = {
    "github-actions", "dependabot", "renovate", "vercel", "cloudflare-pages",
    "azure-pipelines", "nx-cloud", "sonarqubecloud", "sonarcloud", "codecov",
}
FIGMA_URL_RE = re.compile(r"https://(?:www\.)?figma\.com/(?:design|file)/([A-Za-z0-9]+)/[^\s)>\"']*", re.I)
FIGMA_MARK_RE = re.compile(r"<!-- generated by .*?figma_map\.py; edit above this line only -->")


def is_bot(login):
    low = (login or "").lower()
    return not low or low.endswith("[bot]") or low in BOT_LOGINS


def collapse(text, limit=240):
    s = re.sub(r"\s+", " ", (text or "")).strip()
    return s if len(s) <= limit else s[:limit - 1] + "…"


def fetch_threads_graphql(owner, name, n):
    """Fetch all review threads with cursor pagination."""
    query = """
    query($owner:String!, $name:String!, $n:Int!, $cursor:String) {
      repository(owner:$owner, name:$name) {
        pullRequest(number:$n) {
          reviewThreads(first:100, after:$cursor) {
            pageInfo { hasNextPage endCursor }
            nodes {
              id isResolved isOutdated path line originalLine
              comments(first:100) {
                nodes { databaseId author { login } createdAt body commit { oid } }
              }
            }
          }
        }
      }
    }
    """
    nodes, cursor = [], None
    while True:
        cmd = [
            "gh", "api", "graphql",
            "-f", f"query={query}",
            "-f", f"owner={owner}",
            "-f", f"name={name}",
            "-F", f"n={n}",
        ]
        if cursor:
            cmd += ["-f", f"cursor={cursor}"]
        data = json.loads(common.run(cmd).stdout)
        rt = ((data.get("data") or {}).get("repository") or {}).get("pullRequest", {}).get("reviewThreads") or {}
        nodes.extend(rt.get("nodes") or [])
        pi = rt.get("pageInfo") or {}
        if not pi.get("hasNextPage") or not pi.get("endCursor"):
            break
        cursor = pi["endCursor"]
    return nodes


def build_existing_comments(threads, reviews, issue_comments, me):
    ours, peer_open, peer_closed = [], [], []
    for th in threads:
        cs = (th.get("comments") or {}).get("nodes") or []
        if not cs:
            continue
        root = cs[0]
        author = ((root.get("author") or {}).get("login") or "unknown")
        if is_bot(author) and all(is_bot((c.get("author") or {}).get("login")) for c in cs):
            continue
        status = "resolved" if th.get("isResolved") else ("outdated" if th.get("isOutdated") else "open")
        path = th.get("path") or "?"
        line = th.get("line") or th.get("originalLine") or "?"
        db_id = root.get("databaseId") or ""
        entry = f"- [{status}] `{path}:{line}` @{author} (id:{db_id}): {collapse(root.get('body'), 260)}"
        for rep in cs[1:]:
            ra = ((rep.get("author") or {}).get("login") or "unknown")
            entry += f"\n  - reply @{ra} ({(rep.get('createdAt') or '')[:10]}): {collapse(rep.get('body'), 220)}"
        if me and any(((c.get("author") or {}).get("login") or "").lower() == me.lower() for c in cs):
            ours.append(entry)
        elif status == "open":
            peer_open.append(entry)
        else:
            peer_closed.append(entry)

    general = []
    for r in reviews:
        body = (r.get("body") or "").strip()
        author = ((r.get("user") or {}).get("login") or "")
        if not body or is_bot(author):
            continue
        general.append(f"- [review:{r.get('state','')}] @{author} ({(r.get('submitted_at') or '')[:10]}): {collapse(body, 260)}")
    for c in issue_comments:
        body = (c.get("body") or "").strip()
        author = ((c.get("user") or {}).get("login") or "")
        if not body or is_bot(author):
            continue
        general.append(f"- [issue-comment] @{author} ({(c.get('created_at') or '')[:10]}): {collapse(body, 260)}")

    parts = ["# Existing PR Comments\n"]
    parts.append(f"## Our threads ({len(ours)})\n" + ("\n".join(ours) if ours else "none") + "\n")
    parts.append(f"## Other reviewers' open threads ({len(peer_open)})\n" + ("\n".join(peer_open) if peer_open else "none") + "\n")
    parts.append(f"## Other reviewers' resolved/outdated threads ({len(peer_closed)})\n" + ("\n".join(peer_closed) if peer_closed else "none") + "\n")
    parts.append(f"## PR reviews & issue comments ({len(general)})\n" + ("\n".join(general) if general else "none") + "\n")
    return "\n".join(parts), len(ours), len(peer_open)


def prune_and_setup_worktree(repo_dir, out_dir, pr_num, head_sha):
    common.run(["git", "-C", repo_dir, "worktree", "prune"], check=False)
    wt_list = common.run(["git", "-C", repo_dir, "worktree", "list", "--porcelain"], check=False).stdout
    now = time.time()
    cur_wt = None
    target_wt = os.path.abspath(os.path.join(out_dir, "head"))
    for line in wt_list.splitlines() + [""]:
        if line.startswith("worktree "):
            cur_wt = line.split(" ", 1)[1].strip()
        elif line == "" and cur_wt:
            if "/review-pr/" in cur_wt and os.path.abspath(cur_wt) != target_wt:
                try:
                    mtime = os.path.getmtime(cur_wt)
                    if now - mtime > 48 * 3600:
                        common.run(["git", "-C", repo_dir, "worktree", "remove", "--force", cur_wt], check=False)
                except OSError:
                    pass
            cur_wt = None

    common.run(["git", "-C", repo_dir, "fetch", "origin", f"pull/{pr_num}/head"])
    head_dir = os.path.join(out_dir, "head")
    if os.path.isdir(head_dir):
        cur = common.run(["git", "-C", head_dir, "rev-parse", "HEAD"], check=False).stdout.strip()
        if cur == head_sha:
            return head_dir
        common.run(["git", "-C", repo_dir, "worktree", "remove", "--force", head_dir], check=False)
        if os.path.exists(head_dir):
            shutil.rmtree(head_dir, ignore_errors=True)
    common.run(["git", "-C", repo_dir, "worktree", "add", "--detach", head_dir, head_sha])
    return head_dir


def extract_related_notes(reviews_dir, note_fm):
    rel = note_fm.get("related")
    if not rel or not reviews_dir:
        return "none\n"
    if isinstance(rel, str):
        ids = re.findall(r"\d+", rel)
    elif isinstance(rel, list):
        ids = [x for item in rel for x in re.findall(r"\d+", str(item))]
    else:
        ids = re.findall(r"\d+", str(rel))
    if not ids:
        return "none\n"
    sections_keep = ("what we suggested", "outcome", "decision", "notes", "still open")
    out = []
    for rid in ids:
        rp = common.find_pr_note(reviews_dir, rid)
        if not rp:
            continue
        _, body = common.parse_front_matter(rp)
        chunks = re.split(r"(?m)^(?=## )", body)
        kept = [f"# Related PR #{rid} ({os.path.basename(rp)})\n"]
        for ch in chunks:
            first = ch.splitlines()[0].lstrip("# ").strip().lower() if ch.splitlines() else ""
            if any(first.startswith(k) for k in sections_keep):
                kept.append(ch.strip())
        if len(kept) > 1:
            out.append("\n\n".join(kept))
    return ("\n\n---\n\n".join(out) + "\n") if out else "none\n"


def find_instructions_chain(head_dir, files):
    """Collect AGENTS.md / CLAUDE.md / copilot-instructions along changed file paths."""
    found = set()
    for root_cand in ("AGENTS.md", "CLAUDE.md", ".github/copilot-instructions.md"):
        if os.path.isfile(os.path.join(head_dir, root_cand)):
            found.add(root_cand)
    for f in files:
        cur = os.path.dirname(f)
        while cur:
            for name in ("AGENTS.md", "CLAUDE.md"):
                cand = os.path.join(head_dir, cur, name)
                if os.path.isfile(cand):
                    found.add(os.path.join(cur, name))
            parent = os.path.dirname(cur)
            if parent == cur:
                break
            cur = parent
    return sorted(found, key=lambda p: (p.count("/"), p))


def extract_designs(pr_json, issue_comments, threads):
    texts = [pr_json.get("body") or ""]
    texts += [c.get("body") or "" for c in issue_comments]
    for th in threads:
        for c in (th.get("comments") or {}).get("nodes") or []:
            texts.append(c.get("body") or "")
    seen, lines = set(), []
    for t in texts:
        for m in FIGMA_URL_RE.finditer(t):
            url = m.group(0).rstrip(".,);]")
            if url in seen:
                continue
            seen.add(url)
            fkey = m.group(1)
            nm = re.search(r"node-id=([0-9]+[-:][0-9]+)", url)
            nid = nm.group(1).replace("-", ":") if nm else "none"
            lines.append(f"- {url} (file_key: `{fkey}`, node_id: `{nid}`)")
    return ("\n".join(lines) + "\n") if lines else "none found\n"


def extract_design_keywords(head_dir, ui_files):
    routes, names, strings = set(), set(), set()
    skip_segs = {"apps", "libs", "packages", "src", "components", "pages", "views", "display", "layout", "ui"}
    for p in ui_files:
        for seg in p.split("/"):
            if seg in skip_segs:
                continue
            stem = re.sub(r"\.(tsx|jsx|ts|js|vue|svelte|scss|css|less|module\.scss|messages\.ts|messages\.tsx)$", "", seg)
            if stem and stem not in ("index", "types", "helpers", "constants", "utils"):
                words = re.sub(r"([a-z])([A-Z])", r"\1 \2", stem.replace("-", " ").replace("_", " ")).strip()
                if words:
                    names.add(words)
        m = re.search(r"(?:pages|views|routes|app)/(.+?)/[^/]+$", p)
        if m:
            routes.add(m.group(1))
        if ".messages." in p or "/i18n/" in p or "/locales/" in p:
            fp = os.path.join(head_dir, p)
            if os.path.isfile(fp):
                txt = open(fp, encoding="utf-8", errors="replace").read()
                for sm in re.finditer(r"defaultMessage\s*:\s*['\"]([^'\"\n]{2,80})['\"]", txt):
                    strings.add(sm.group(1).strip())
    out = []
    if routes:
        out.append("## Route segments\n" + "\n".join(f"- {r}" for r in sorted(routes)))
    if names:
        out.append("## Component & page terms\n" + "\n".join(f"- {n}" for n in sorted(names)[:40]))
    if strings:
        out.append("## Visible i18n strings\n" + "\n".join(f"- {s}" for s in sorted(strings)[:40]))
    return ("\n\n".join(out) + "\n") if out else "none\n"


def slice_figma_map(figma_map_path, ui_files):
    fp = common.expand_path(figma_map_path)
    if not fp or not os.path.isfile(fp):
        return "Figma map not configured or not found\n", []
    text = open(fp, encoding="utf-8", errors="replace").read()
    parts = FIGMA_MARK_RE.split(text, maxsplit=1)
    top = parts[0]
    gen = parts[1] if len(parts) > 1 else ""

    matched_rows, matched_files = [], set()
    for line in top.splitlines():
        if not line.startswith("|") or line.startswith("|---") or "| App area |" in line:
            continue
        cols = [c.strip() for c in line.strip("|").split("|")]
        if len(cols) < 4:
            continue
        code_col, figma_col = cols[2], cols[3]
        tokens = [t.strip("` ") for t in re.findall(r"`([^`]+)`", code_col)]
        if any(tok in p for tok in tokens for p in ui_files):
            matched_rows.append(line)
            for part in figma_col.split(";"):
                fname = part.split("→")[0].split("(")[0].strip()
                if fname:
                    matched_files.add(fname.lower())
                    matched_files.add(fname.split("|")[0].strip().lower())

    if not matched_rows:
        idx = gen.find("## Projects and files")
        proj_end = gen.find("\n## ", idx + 10) if idx != -1 else -1
        proj_table = gen[:proj_end].strip() if proj_end != -1 else gen[:4000]
        body = (
            f"{top.strip()}\n\n{proj_table}\n\n"
            f"(No folder matched directly in By app area. Full frame index is at `{fp}`.)\n"
        )
        return body, []

    sections = []
    if gen:
        for ch in re.split(r"(?m)^(?=## )", gen):
            hdr = ch.splitlines()[0].lstrip("# ").strip().lower() if ch.splitlines() else ""
            if hdr == "projects and files":
                continue
            if any(hdr == mf or mf in hdr or hdr in mf for mf in matched_files if len(mf) >= 3):
                sections.append(ch.strip())

    out = [
        "# Matched Figma Map Slice\n",
        f"(Full map at `{fp}` if you need other files.)\n",
        "## Matching app areas",
        "| App area | Routes | Code | Figma file → page |",
        "|---|---|---|---|",
        *matched_rows,
        "",
        *sections,
    ]
    return "\n".join(out) + "\n", sorted(matched_files)


def run_extra_linters(repo_dir, head_dir, candidate_files, linters_cfg, out_dir):
    """Run optional configured linters (e.g. stylelint) that don't run in CI."""
    statuses = {}
    combined_report = []
    for lcfg in linters_cfg or []:
        name = lcfg.get("name") or "linter"
        exts = tuple(lcfg.get("extensions") or [])
        out_name = lcfg.get("output_file") or f"{name}.txt"
        out_path = os.path.join(out_dir, out_name)
        matched = [
            os.path.join(head_dir, f)
            for f in candidate_files
            if (not exts or f.endswith(exts)) and os.path.isfile(os.path.join(head_dir, f))
        ]
        if not matched:
            open(out_path, "w", encoding="utf-8").write(f"no matching files changed for {name}\n")
            statuses[name] = "skipped (no matching files)"
            continue
        cmd_tpl = lcfg.get("command") or []
        if isinstance(cmd_tpl, str):
            cmd_tpl = shlex.split(cmd_tpl)
        if not cmd_tpl:
            statuses[name] = "skipped (no command)"
            continue
        exe = cmd_tpl[0]
        if not shutil.which(exe):
            msg = f"{name} unavailable: {exe} not found in PATH\n"
            open(out_path, "w", encoding="utf-8").write(msg)
            statuses[name] = f"unavailable ({exe} not found)"
            continue
        cmd = [*cmd_tpl, *matched]
        r = common.run(cmd, cwd=repo_dir, check=False)
        combined = (r.stdout or "") + (("\n" + r.stderr) if r.stderr else "")
        body = combined.strip() + "\n" if combined.strip() else "clean (0 errors)\n"
        open(out_path, "w", encoding="utf-8").write(body)
        status = "clean" if r.returncode == 0 else f"issues found (exit {r.returncode})"
        statuses[name] = status
        combined_report.append(f"## {name} ({status})\n\n{body}")

    report_path = os.path.join(out_dir, "linters.txt")
    if combined_report:
        open(report_path, "w", encoding="utf-8").write("\n".join(combined_report))
    else:
        open(report_path, "w", encoding="utf-8").write("no extra linters configured or matched\n")
    return statuses


def collect_tickets(pr_json, tracker_cfg):
    if (tracker_cfg or {}).get("type", "none") == "none":
        return [], None
    pat_str = (tracker_cfg or {}).get("pattern") or r"#(\d+)"
    pat = re.compile(pat_str, re.I)

    def extract(text):
        hits = []
        for m in pat.finditer(text or ""):
            groups = [g for g in m.groups() if g]
            val = groups[0] if groups else m.group(0)
            if val not in hits:
                hits.append(val)
        return hits

    primary_src = f"{pr_json.get('title') or ''} {pr_json.get('headRefName') or ''}"
    primary = extract(primary_src)
    other_src = (pr_json.get("body") or "") + " " + " ".join(
        (c.get("messageHeadline") or "") + " " + (c.get("messageBody") or "")
        for c in (pr_json.get("commits") or [])
    )
    all_ids = list(dict.fromkeys(primary + extract(other_src)))
    return all_ids, (primary[0] if primary else (all_ids[0] if all_ids else None))


def infer_old_head_from_github(reviews, threads_gql, me):
    """Fallback for docs.mode='none': find commit SHA of our most recent review/comment."""
    if not me:
        return None
    candidates = []
    for r in reviews or []:
        author = ((r.get("user") or {}).get("login") or "").lower()
        cid = r.get("commit_id")
        ts = r.get("submitted_at") or ""
        if author == me.lower() and cid:
            candidates.append((ts, cid))
    for th in threads_gql or []:
        for c in (th.get("comments") or {}).get("nodes") or []:
            author = ((c.get("author") or {}).get("login") or "").lower()
            cid = (c.get("commit") or {}).get("oid")
            ts = c.get("createdAt") or ""
            if author == me.lower() and cid:
                candidates.append((ts, cid))
    if not candidates:
        return None
    candidates.sort(key=lambda pair: pair[0])
    return candidates[-1][1]


def gather_recheck_info(repo_dir, pr_num, pr_json, pr_diff_files, out_dir, cli_old_head, note_fm, data_dir, reviews, threads_gql, me):
    old_head = cli_old_head or note_fm.get("head")
    old_head_source = "cli" if cli_old_head else ("note" if old_head else "")
    if not old_head and data_dir:
        rounds = sorted(glob.glob(os.path.join(data_dir, str(pr_num), "round-*.json")))
        if rounds:
            try:
                old_head = json.load(open(rounds[-1], encoding="utf-8")).get("head")
                if old_head:
                    old_head_source = "round-json"
            except Exception:
                pass
    if not old_head:
        old_head = infer_old_head_from_github(reviews, threads_gql, me)
        if old_head:
            old_head_source = "github-history"

    new_head = pr_json["headRefOid"]
    base_ref = pr_json.get("baseRefName") or "main"
    rebased = False
    commits_txt = ""
    recheck_diff = ""
    changed_since = []
    reverted = []

    if old_head:
        has_old = common.run(["git", "-C", repo_dir, "cat-file", "-e", f"{old_head}^{{commit}}"], check=False).returncode == 0
        if not has_old:
            common.run(["git", "-C", repo_dir, "fetch", "origin", old_head], check=False)
            has_old = common.run(["git", "-C", repo_dir, "cat-file", "-e", f"{old_head}^{{commit}}"], check=False).returncode == 0
        if has_old:
            commits_txt = common.run(
                ["git", "-C", repo_dir, "log", "--first-parent", "--no-merges", "--oneline", f"{old_head}..{new_head}"],
                check=False,
            ).stdout.strip()
            touched_non_merge = set(
                f for f in common.run(
                    ["git", "-C", repo_dir, "log", "--first-parent", "--no-merges", "--name-only", "--pretty=format:", f"{old_head}..{new_head}"],
                    check=False,
                ).stdout.splitlines() if f.strip()
            )
            scope = sorted(set(pr_diff_files) | touched_non_merge)
            if scope:
                recheck_diff = common.run(
                    ["git", "-C", repo_dir, "diff", old_head, new_head, "--", *scope],
                    check=False,
                ).stdout
                changed_since = [
                    f for f in common.run(
                        ["git", "-C", repo_dir, "diff", "--name-only", old_head, new_head, "--", *scope],
                        check=False,
                    ).stdout.splitlines() if f.strip()
                ]
            reverted = sorted(touched_non_merge - set(pr_diff_files))
        else:
            rebased = True

    if not old_head or rebased:
        common.run(["git", "-C", repo_dir, "fetch", "origin", base_ref], check=False)
        recheck_diff = common.run(
            ["git", "-C", repo_dir, "diff", f"origin/{base_ref}...{new_head}"],
            check=False,
        ).stdout
        changed_since = list(pr_diff_files)

    open(os.path.join(out_dir, "recheck.diff"), "w", encoding="utf-8").write(recheck_diff)
    info = [
        f"# Recheck Info (#{pr_num})",
        f"- old_head: `{old_head or 'unknown'}` (source: `{old_head_source or 'none'}`)",
        f"- new_head: `{new_head}`",
        f"- rebased_or_missing_old_head: `{rebased}`",
        f"- changed_files_since_old_head ({len(changed_since)}): " + (", ".join(f"`{f}`" for f in changed_since[:30]) or "none"),
        f"- reverted_files_dropped_from_pr_diff ({len(reverted)}): " + (", ".join(f"`{f}`" for f in reverted) or "none"),
        "",
        "## Non-merge commits since old_head",
        commits_txt or "(none — merge-only or force-pushed)",
        "",
    ]
    open(os.path.join(out_dir, "recheck-info.md"), "w", encoding="utf-8").write("\n".join(info))
    return {
        "old_head": old_head,
        "old_head_source": old_head_source,
        "rebased": rebased,
        "changed_since": changed_since,
        "reverted": reverted,
    }


def detect_stacks(files, routing_cfg):
    stack_prefixes = routing_cfg.get("stack_prefixes") or {}
    if stack_prefixes:
        stacks = [
            name for name, prefixes in stack_prefixes.items()
            if any(f.startswith(tuple(prefixes)) for f in files)
        ]
        return stacks or ["config"]

    # Generic language-based stack detection when no stack_prefixes are configured
    stacks = []
    if any(f.endswith((".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".vue", ".svelte", ".scss", ".css")) for f in files):
        stacks.append("frontend")
    if any(f.endswith((".java", ".kt", ".go", ".rs", ".py", ".rb", ".cs", ".php")) for f in files):
        stacks.append("backend")
    return stacks or ["config"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pr", type=int)
    ap.add_argument("--dir", required=True, dest="out_dir")
    ap.add_argument("--mode", choices=("review", "recheck"), default="review")
    ap.add_argument("--old-head", default=None)
    ap.add_argument("--repo", default=None, help="Path to local git repository (default: current git root)")
    ap.add_argument("--gh-repo", default=None, help="GitHub owner/repo (default: auto-detected from origin)")
    ap.add_argument("--no-linters", action="store_true")
    args = ap.parse_args()

    out_dir = os.path.abspath(args.out_dir)
    os.makedirs(out_dir, exist_ok=True)

    repo_dir = common.detect_git_root(args.repo)
    base_cfg = common.load_config()
    gh_repo = args.gh_repo or common.detect_gh_repo(repo_dir, base_cfg)
    if not gh_repo or "/" not in gh_repo:
        raise RuntimeError("Could not detect GitHub owner/repo. Pass --gh-repo owner/repo or run inside a git checkout.")
    owner, repo_name = gh_repo.split("/", 1)

    cfg = common.effective_config(gh_repo)
    _, repo_md, repo_md_path = common.load_repo_profile(gh_repo)
    me = common.detect_github_login(cfg)
    docs_mode, reviews_dir, data_dir = common.docs_paths(cfg, gh_repo)

    pr_raw = common.run([
        "gh", "pr", "view", str(args.pr), "-R", gh_repo, "--json",
        "number,title,body,author,files,additions,deletions,headRefName,baseRefName,headRefOid,commits,url,isDraft",
    ]).stdout
    pr_json = json.loads(pr_raw)
    open(os.path.join(out_dir, "pr.json"), "w", encoding="utf-8").write(json.dumps(pr_json, indent=2))

    diff_text = common.run(["gh", "pr", "diff", str(args.pr), "-R", gh_repo]).stdout
    open(os.path.join(out_dir, "pr.diff"), "w", encoding="utf-8").write(diff_text)
    empty_diff = not diff_text.strip()

    threads_rest = json.loads(common.run(["gh", "api", f"repos/{gh_repo}/pulls/{args.pr}/comments", "--paginate"]).stdout or "[]")
    reviews = json.loads(common.run(["gh", "api", f"repos/{gh_repo}/pulls/{args.pr}/reviews", "--paginate"]).stdout or "[]")
    issue_comments = json.loads(common.run(["gh", "api", f"repos/{gh_repo}/issues/{args.pr}/comments", "--paginate"]).stdout or "[]")
    threads_gql = fetch_threads_graphql(owner, repo_name, args.pr)

    open(os.path.join(out_dir, "threads.json"), "w", encoding="utf-8").write(json.dumps(threads_rest, indent=2))
    open(os.path.join(out_dir, "reviews.json"), "w", encoding="utf-8").write(json.dumps(reviews, indent=2))
    open(os.path.join(out_dir, "issue-comments.json"), "w", encoding="utf-8").write(json.dumps(issue_comments, indent=2))
    open(os.path.join(out_dir, "thread-status.json"), "w", encoding="utf-8").write(json.dumps(threads_gql, indent=2))

    existing_md, our_threads, peer_open_threads = build_existing_comments(threads_gql, reviews, issue_comments, me)
    open(os.path.join(out_dir, "existing-comments.md"), "w", encoding="utf-8").write(existing_md)

    head_dir = prune_and_setup_worktree(repo_dir, out_dir, args.pr, pr_json["headRefOid"])

    note_path = common.find_pr_note(reviews_dir, args.pr) if reviews_dir else None
    note_fm = common.parse_front_matter(note_path)[0] if note_path else {}
    next_round = common.next_round_number(data_dir, args.pr, note_fm)
    round_path = (
        os.path.join(data_dir, str(args.pr), f"round-{next_round}.json")
        if data_dir
        else os.path.join(out_dir, f"round-{next_round}.json")
    )

    author_obj = pr_json.get("author") or {}
    author_login = author_obj.get("login") or ""
    author_name = note_fm.get("author_name") or author_obj.get("name") or ""
    author_cfg = cfg.get("author_notes") or {}
    if author_cfg.get("mode", "propose") != "off" and author_login:
        authors_mod.touch_author(author_login, name=author_name, pr_num=args.pr, gh_repo=gh_repo)
    author_notes_txt = authors_mod.extract_notes_for_context(
        author_login,
        display_name=author_name,
        extra_files=author_cfg.get("extra_files") or [],
    )
    open(os.path.join(out_dir, "author-notes.md"), "w", encoding="utf-8").write(author_notes_txt)
    open(os.path.join(out_dir, "related.md"), "w", encoding="utf-8").write(extract_related_notes(reviews_dir, note_fm))
    open(os.path.join(out_dir, "repo-profile.md"), "w", encoding="utf-8").write(repo_md or "none\n")

    files = [f["path"] for f in (pr_json.get("files") or []) if f.get("path")]
    agents_chain = find_instructions_chain(head_dir, files)
    open(os.path.join(out_dir, "agents-chain.md"), "w", encoding="utf-8").write("\n".join(agents_chain) + "\n")

    recheck_meta = None
    if args.mode == "recheck":
        recheck_meta = gather_recheck_info(
            repo_dir, args.pr, pr_json, files, out_dir, args.old_head, note_fm, data_dir, reviews, threads_gql, me
        )

    linter_candidates = (recheck_meta["changed_since"] if (recheck_meta and recheck_meta["changed_since"]) else files)
    if args.no_linters:
        linter_statuses = {"all": "skipped (--no-linters)"}
    else:
        linter_statuses = run_extra_linters(repo_dir, head_dir, linter_candidates, cfg.get("extra_linters"), out_dir)

    routing = cfg.get("routing") or {}
    ui_exts = tuple(routing.get("ui_extensions") or [".tsx", ".jsx", ".scss", ".css"])
    ui_files = [f for f in files if f.endswith(ui_exts) and not re.search(r"\.(test|spec|stories)\.", f)]
    has_ui = bool(ui_files)
    design_cfg = cfg.get("design") or {}
    figma_matches = []
    if has_ui and args.mode == "review":
        open(os.path.join(out_dir, "designs.md"), "w", encoding="utf-8").write(extract_designs(pr_json, issue_comments, threads_gql))
        open(os.path.join(out_dir, "design-keywords.md"), "w", encoding="utf-8").write(extract_design_keywords(head_dir, files))
        fslice, figma_matches = slice_figma_map(design_cfg.get("figma_map") or "", ui_files)
        open(os.path.join(out_dir, "figma-files.md"), "w", encoding="utf-8").write(fslice)

    stacks = detect_stacks(files, routing)
    sens_path_re = re.compile(routing.get("sensitive_path_regex") or r"(auth|payment|secret)", re.I)
    sens_diff_re = re.compile(routing.get("sensitive_diff_regex") or r"(client_?secret|dangerouslySetInnerHTML)", re.I)

    sensitive_reasons = []
    for f in files:
        if sens_path_re.search(f):
            sensitive_reasons.append(f"path:{f}")
            if len(sensitive_reasons) >= 3:
                break
    if not sensitive_reasons and sens_diff_re.search(diff_text):
        sensitive_reasons.append("diff:security/payment keyword")

    additions = int(pr_json.get("additions") or 0)
    deletions = int(pr_json.get("deletions") or 0)
    total_lines = additions + deletions

    cross_groups = routing.get("cross_stack_groups") or []
    if cross_groups:
        cross_stack = all(any(s in stacks for s in grp) for grp in cross_groups)
    else:
        cross_stack = len(stacks) > 1 and "config" not in stacks

    is_sensitive = bool(sensitive_reasons)
    shared_prefixes = tuple(routing.get("shared_prefixes") or ["libs/", "packages/", "shared/"])
    touches_shared = any(f.startswith(shared_prefixes) for f in files)
    escalate_min = int(routing.get("escalate_min_lines") or 800)
    wide_or_shared = cross_stack or touches_shared or total_lines > escalate_min
    small_max_files = int(routing.get("small_diff_max_files") or 5)
    small_max_lines = int(routing.get("small_diff_max_lines") or 50)
    small_diff_eligible = (
        len(files) <= small_max_files
        and total_lines <= small_max_lines
        and not is_sensitive
        and not has_ui
        and not cross_stack
    )
    ticket_ids, main_ticket = collect_tickets(pr_json, cfg.get("issue_tracker"))

    meta = {
        "pr": args.pr,
        "gh_repo": gh_repo,
        "repo_dir": repo_dir,
        "mode": args.mode,
        "head": pr_json["headRefOid"],
        "base": pr_json.get("baseRefName"),
        "reviewer": me,
        "author": author_login,
        "author_name": author_name,
        "author_profile": authors_mod.author_path(author_login) if author_login else "",
        "is_self_pr": bool(me and author_login.lower() == me.lower()),
        "empty_diff": empty_diff,
        "files_count": len(files),
        "additions": additions,
        "deletions": deletions,
        "total_lines": total_lines,
        "stacks": stacks,
        "has_ui": has_ui,
        "ui_files_count": len(ui_files),
        "design_mode": design_cfg.get("mode", "off"),
        "is_sensitive": is_sensitive,
        "sensitive_reasons": sensitive_reasons,
        "cross_stack": cross_stack,
        "escalate_general": is_sensitive or wide_or_shared,
        "split_general_by_language": cross_stack and (is_sensitive or total_lines > escalate_min),
        "general_effort": "medium" if is_sensitive else "low",
        "small_diff_eligible": small_diff_eligible,
        "issue_tracker": (cfg.get("issue_tracker") or {}).get("type", "none"),
        "ticket_ids": ticket_ids,
        "main_ticket": main_ticket,
        "agents_chain": agents_chain,
        "repo_profile_path": repo_md_path or "",
        "our_threads": our_threads,
        "peer_open_threads": peer_open_threads,
        "linters": linter_statuses,
        "figma_matches": figma_matches,
        "docs_mode": docs_mode,
        "reviews_dir": reviews_dir or "",
        "note_path": note_path or "",
        "next_round": next_round,
        "round_path": round_path,
        "state_dir": common.state_dir(),
        "recheck": recheck_meta,
    }
    open(os.path.join(out_dir, "meta.json"), "w", encoding="utf-8").write(json.dumps(meta, indent=2))
    print(
        f"gathered {gh_repo}#{args.pr} ({args.mode}) at {pr_json['headRefOid'][:7]}: "
        f"{len(files)} files (+{additions}/-{deletions}), stacks={','.join(stacks)}, "
        f"ui={has_ui}, sensitive={is_sensitive}, small_fast_path={small_diff_eligible}, "
        f"tickets={','.join(ticket_ids) or 'none'}, threads(ours={our_threads}, peer_open={peer_open_threads}), "
        f"docs={docs_mode}, linters={linter_statuses or 'none'}"
    )


if __name__ == "__main__":
    sys.exit(main())
